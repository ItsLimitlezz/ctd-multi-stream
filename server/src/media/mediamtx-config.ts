// MediaMTX configuration generator (pure). Field names checked against the mediamtx.yml shipped
// with v1.21.2: https://github.com/bluenviron/mediamtx/blob/v1.21.2/mediamtx.yml
// MediaMTX rejects unknown keys, so only emit fields that exist in the pinned version.

import { FEEDS } from '../../../shared/types.js';
import { feedPath } from './paths.js';

export interface MediaMtxConfigOptions {
  /** RTMP ingest port (all interfaces; OBS is on the LAN). */
  rtmpPort: number;
  /** Control API port (bound to 127.0.0.1). */
  apiPort: number;
  /** Port of our loopback auth server (POST /auth). */
  authPort: number;
  logLevel?: 'error' | 'warn' | 'info' | 'debug';
}

function q(value: string): string {
  return JSON.stringify(value); // a JSON string is a valid double-quoted YAML scalar
}

function port(n: number, name: string): number {
  if (!Number.isInteger(n) || n < 1 || n > 65535) throw new Error(`Invalid ${name}: ${n}`);
  return n;
}

export function buildMediaMtxConfig(opts: MediaMtxConfigOptions): string {
  const rtmpPort = port(opts.rtmpPort, 'rtmpPort');
  const apiPort = port(opts.apiPort, 'apiPort');
  const authPort = port(opts.authPort, 'authPort');

  const lines = [
    '# Generated by CTD Multi-Stream on every start. Manual edits are overwritten.',
    '',
    `logLevel: ${opts.logLevel ?? 'info'}`,
    'logDestinations: [stdout]',
    'logStructured: false',
    'readTimeout: 10s',
    'writeTimeout: 10s',
    '',
    '# Every publish/read is decided by the app (loopback HTTP). The API is loopback-only.',
    'authMethod: http',
    `authHTTPAddress: ${q(`http://127.0.0.1:${authPort}/auth`)}`,
    'authHTTPExclude:',
    '  - action: api',
    '  - action: metrics',
    '',
    'api: true',
    `apiAddress: ${q(`127.0.0.1:${apiPort}`)}`,
    'metrics: false',
    'pprof: false',
    'playback: false',
    '',
    'rtmp: true',
    'rtmpEncryption: "no"',
    `rtmpAddress: ${q(`:${rtmpPort}`)}`,
    '',
    'rtsp: false',
    'hls: false',
    'webrtc: false',
    'srt: false',
    'moq: false',
    '',
    'pathDefaults:',
    '  source: publisher',
    '  # Lets OBS reconnect while its previous (dead) connection is still being torn down.',
    '  overridePublisher: true',
    '  record: false',
    '',
    '# Only the two feeds exist; any other path is rejected by MediaMTX.',
    'paths:',
    ...FEEDS.flatMap((feed) => [`  ${feedPath(feed)}:`, '    source: publisher']),
    '',
  ];
  return lines.join('\n');
}
